import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { workoutLogSchema, workoutTemplateSchema } from "@openweight/sdk";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone";

const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(workoutTemplateSchema);
const validate = ajv.compile(workoutLogSchema);

const scratch = await mkdtemp(join(import.meta.dirname, ".generate-"));
const entry = join(scratch, "validator.js");
await writeFile(entry, standaloneCode(ajv, validate));
const built = await Bun.build({ entrypoints: [entry], format: "esm", target: "browser", minify: true });
await rm(scratch, { recursive: true });
const [output] = built.outputs;
if (!built.success || output === undefined) throw new AggregateError(built.logs, "Bundling the validator failed");

const out = resolve(import.meta.dirname, "workout-log-validator.js");
await writeFile(out, `// Generated by tools/workouts/openweight/generate.ts from @openweight/sdk 0.13.0. Do not edit.\n${await output.text()}`);
console.log(`Wrote ${out}`);
